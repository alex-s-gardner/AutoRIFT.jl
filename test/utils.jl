# Assertion macros
# ---------------------------------------------------------------------------

"""
    @test_identical a b

Assert two arrays are bit-for-bit identical, including `NaN` payloads and the
sign of zero.

`isequal` already treats `NaN === NaN` and distinguishes `-0.0` from `0.0`, but
elementwise `==` does not, and `≈` hides exactly the class of error this suite
exists to catch. Used wherever a computation is expected to reproduce a
reference exactly.
"""
macro test_identical(a, b)
    quote
        local x, y = $(esc(a)), $(esc(b))
        @test size(x) == size(y)
        @test all(isequal.(x, y))
    end
end

"""
    @test_approx a b atol rtol

Assert two arrays agree to a tolerance, treating `NaN` as equal to `NaN` so that
masked-out pixels compare cleanly. Reports the worst offending index on failure,
which a bare `≈` does not.
"""
macro test_approx(a, b, atol = 1e-6, rtol = 1e-6)
    quote
        local x, y = $(esc(a)), $(esc(b))
        local at, rt = $(esc(atol)), $(esc(rtol))
        @test size(x) == size(y)
        local worst_i, worst_d = nothing, 0.0
        for i in eachindex(x, y)
            (isnan(x[i]) && isnan(y[i])) && continue
            local d = abs(float(x[i]) - float(y[i]))
            local tol = at + rt * max(abs(float(x[i])), abs(float(y[i])))
            if d > tol && d > worst_d
                worst_i, worst_d = i, d
            end
        end
        if isnothing(worst_i)
            @test true
        else
            @test worst_d == 0.0 || error(
                "arrays differ at index $worst_i: $(x[worst_i]) vs " *
                "$(y[worst_i]) (Δ = $worst_d, atol = $at, rtol = $rt)")
        end
    end
end

"""
    @test_divergence a b max_fraction

Assert that at most `max_fraction` of elements differ between two arrays.

The correctness gate for comparisons where exact agreement is not expected
*and not wanted* — this package deliberately fixes several defects in the Python
reference, so a handful of pixels legitimately choose a different correlation
peak. Rather than loosening the assertion to meaninglessness, the fraction that
differs is bounded and tracked: a regression shows up as the count rising.

`NaN` in the same position in both arrays counts as agreement.
"""
macro test_divergence(a, b, max_fraction)
    quote
        local x, y = $(esc(a)), $(esc(b))
        local maxfrac = $(esc(max_fraction))
        @test size(x) == size(y)
        local ndiff = 0
        for i in eachindex(x, y)
            isequal(x[i], y[i]) && continue
            (isnan(x[i]) && isnan(y[i])) && continue
            ndiff += 1
        end
        local frac = ndiff / length(x)
        if frac > maxfrac
            error("$ndiff of $(length(x)) elements differ ($(round(100frac, digits=3))%), " *
                  "budget is $(round(100maxfrac, digits=3))%")
        end
        @test frac <= maxfrac
    end
end

