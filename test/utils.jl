# Test helpers: fixture loading and the assertion macros the suite is built on.

using Test
using JSON3

const FIXTURE_DIR = joinpath(@__DIR__, "fixtures")
const MANIFEST_PATH = joinpath(FIXTURE_DIR, "manifest.json")

"""
    fixture(name) -> NamedTuple

Load the reference arrays for case `name` from `test/fixtures/`.

Fixtures are generated by `tools/python_ref/gen_fixtures.py` against a pinned
OpenCV/NumPy environment and committed, so the test suite runs on a bare clone
with no Python present. See `tools/python_ref/README.md` to regenerate.

Each fixture is a directory holding one `.bin` per array plus a `meta.json`
describing shapes, element types, and the parameters the case was generated
with. A flat binary format is used rather than `.npz` so that loading needs no
Python-format reader.
"""
function fixture(name::AbstractString)
    dir = joinpath(FIXTURE_DIR, name)
    isdir(dir) || throw(ArgumentError(
        "fixture \"$name\" not found at $dir. Run " *
        "`julia --project=. tools/python_ref/gen_fixtures.jl` or see " *
        "tools/python_ref/README.md."))
    meta = JSON3.read(read(joinpath(dir, "meta.json"), String))
    arrays = Dict{Symbol,Any}()
    for (key, spec) in pairs(meta.arrays)
        T = _fixture_eltype(String(spec.dtype))
        dims = Tuple(Int.(spec.shape))
        raw = read(joinpath(dir, String(key) * ".bin"))
        expected = prod(dims) * sizeof(T)
        length(raw) == expected || error(
            "fixture $name/$key: expected $expected bytes for " *
            "$dims $T, got $(length(raw))")
        # Python writes C-order (row-major); reading into the reversed shape and
        # permuting gives the same logical array in Julia's column-major layout.
        arrays[Symbol(key)] = permutedims(reshape(reinterpret(T, raw), reverse(dims)),
                                          ndims_perm(length(dims)))
    end
    return (; arrays = NamedTuple(arrays), params = meta.params)
end

ndims_perm(n::Int) = ntuple(i -> n - i + 1, n)

function _fixture_eltype(s::AbstractString)
    T = get(FIXTURE_DTYPES, s, nothing)
    isnothing(T) && throw(ArgumentError("unsupported fixture dtype \"$s\""))
    return T
end

const FIXTURE_DTYPES = Dict{String,DataType}(
    "uint8" => UInt8, "int8" => Int8,
    "uint16" => UInt16, "int16" => Int16,
    "uint32" => UInt32, "int32" => Int32,
    "uint64" => UInt64, "int64" => Int64,
    "float32" => Float32, "float64" => Float64,
    "complex64" => ComplexF32, "complex128" => ComplexF64,
    "bool" => Bool,
)

"""
    has_fixtures() -> Bool

Whether the fixture corpus is present. Tests that compare against OpenCV are
skipped when it is not, so a bare clone still runs the truth-based suite.
"""
has_fixtures() = isfile(MANIFEST_PATH)

