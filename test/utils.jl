# Synthetic test data
# ---------------------------------------------------------------------------

"""
    synthetic_texture(sz; seed = 0, T = Float32) -> Matrix{T}

A band-limited random texture suitable for correlation tests.

White noise is a poor test input: it correlates only at exactly zero lag, so a
peak is found but nothing is learned about the shape of the correlation surface
or about subpixel behaviour. Smoothing the noise produces a surface with a
finite-width peak, which is both more realistic and a stricter test.
"""
function synthetic_texture(sz::Tuple{Int,Int}; seed::Integer = 0, T::Type = Float32)
    rng = Random.MersenneTwister(seed)
    a = randn(rng, Float64, sz)
    # Three passes of a 3x3 box blur approximate a Gaussian well enough, and
    # keep this helper dependency-free.
    for _ in 1:3
        a = _box3(a)
    end
    a .-= minimum(a)
    m = maximum(a)
    m > 0 && (a ./= m)
    return T <: Integer ? round.(T, a .* typemax(T)) : T.(a)
end

synthetic_texture(n::Integer; kw...) = synthetic_texture((Int(n), Int(n)); kw...)

"""
    rotate_bilinear(img, deg) -> Matrix{Float32}

`img` rotated `deg` degrees about its own centre, by bilinear resampling, with out-of-image samples
zero.

A test helper for the rotation search, and bilinear rather than nearest-neighbour deliberately:
`AutoRIFT._rotate_chip` is bilinear, so a nearest-neighbour scene would make every measurement of the
search a measurement of the *mismatch* between two resamplers. Same sign convention and same
half-pixel centre as `_rotate_chip`, for the same reason.

**Deliberately not a call to `_rotate_chip`, which it near-duplicates.** The test this exists for
asserts that counter-rotating a chip with `_rotate_chip` recovers correlation against an
independently rotated scene. Generating the scene with the same function would let a broken rotator
cancel against itself and the assertion pass regardless — the duplication is what keeps the two
sides independent. (It would also need a full-image `CorrelationWorkspace` and its FFT buffers,
which is beside the point.)
"""
function rotate_bilinear(img::AbstractMatrix, deg::Real)
    nr, nc = size(img)
    yc, xc = (nr + 1) / 2, (nc + 1) / 2
    s, c = sincos(deg2rad(Float64(deg)))
    out = zeros(Float32, nr, nc)
    @inbounds for j in 1:nc, i in 1:nr
        dy, dx = i - yc, j - xc
        sy = yc + c * dy + s * dx
        sx = xc - s * dy + c * dx
        i0, j0 = floor(Int, sy), floor(Int, sx)
        (i0 < 1 || j0 < 1 || i0 + 1 > nr || j0 + 1 > nc) && continue
        fy, fx = sy - i0, sx - j0
        out[i, j] = (1 - fy) * ((1 - fx) * img[i0, j0] + fx * img[i0, j0 + 1]) +
                    fy * ((1 - fx) * img[i0 + 1, j0] + fx * img[i0 + 1, j0 + 1])
    end
    return out
end

function _box3(a::Matrix{Float64})
    out = similar(a)
    nr, nc = size(a)
    @inbounds for j in 1:nc, i in 1:nr
        s, n = 0.0, 0
        for dj in -1:1, di in -1:1
            ii, jj = i + di, j + dj
            if 1 <= ii <= nr && 1 <= jj <= nc
                s += a[ii, jj]
                n += 1
            end
        end
        out[i, j] = s / n
    end
    return out
end

"""
    shifted_pair(sz, shift; seed = 0, T = Float32) -> (reference, secondary)

A synthetic image pair where `secondary` is `reference` displaced by
`shift = (dx, dy)` pixels. Integer shifts are exact; fractional shifts are
produced by bilinear interpolation.

This is the package's primary correctness oracle: unlike a comparison against
the Python reference, the answer here is known exactly rather than merely
agreed upon.
"""
function shifted_pair(sz::Tuple{Int,Int}, shift::Tuple{Real,Real};
                      seed::Integer = 0, T::Type = Float32)
    # Generate oversized so that shifting does not pull in out-of-bounds data,
    # which would otherwise put an artificial edge inside the search window.
    pad = ceil(Int, maximum(abs, shift)) + 2
    big = synthetic_texture((sz[1] + 2pad, sz[2] + 2pad); seed, T = Float64)
    ref = big[(pad + 1):(pad + sz[1]), (pad + 1):(pad + sz[2])]
    sec = _shift_bilinear(big, shift)[(pad + 1):(pad + sz[1]), (pad + 1):(pad + sz[2])]
    conv = T <: Integer ? x -> round(T, clamp(x, 0, 1) * typemax(T)) : x -> T(x)
    return conv.(ref), conv.(sec)
end

shifted_pair(n::Integer, shift; kw...) = shifted_pair((Int(n), Int(n)), shift; kw...)

"""
    chip_and_window(img, centre, chip_size, radius; shift = (0, 0), window_from = img)
        -> (chip, window)

A chip and its search window, cut about `centre = (row, col)` in the layout `correlate!` requires.

The window extent is the delicate part, and it was written out by hand at seven call sites before
this helper existed — in three spellings of the same arithmetic (`+ h + r - 2` and `+ h - 2 + r`
differ textually but not numerically, so grep did not connect them). `correlate!`'s window is
**deliberately asymmetric**: it reaches `radius` one way and `radius - 1` the other, so the surface
is an even `2 * radius` and zero displacement lands on a sample rather than between two. Get the
`-2` wrong and the correlator throws a `DimensionMismatch` that reads as a test bug rather than a
convention error.

`shift` offsets the *chip* only, which is how a known displacement is set up: the window stays put
and the chip is cut from `shift` pixels away, so the peak must land at `shift`.

`window_from` cuts the window from a different image than the chip — the reference/secondary split
that a real pair has.
"""
function chip_and_window(img::AbstractMatrix, centre::Tuple{Integer,Integer},
                         chip_size::Integer, radius::Integer;
                         shift::Tuple{Integer,Integer} = (0, 0),
                         window_from::AbstractMatrix = img)
    cy, cx = centre
    sy, sx = shift
    h = chip_size ÷ 2
    chip = img[(cy - h + sy):(cy + h - 1 + sy), (cx - h + sx):(cx + h - 1 + sx)]
    window = window_from[(cy - h - radius):(cy + h + radius - 2),
                         (cx - h - radius):(cx + h + radius - 2)]
    return chip, window
end

# Sample `a` at (i - dy, j - dx) so the result is `a` translated by (+dx, +dy).
function _shift_bilinear(a::Matrix{Float64}, shift::Tuple{Real,Real})
    dx, dy = Float64(shift[1]), Float64(shift[2])
    nr, nc = size(a)
    out = similar(a)
    @inbounds for j in 1:nc, i in 1:nr
        y, x = i - dy, j - dx
        i0, j0 = floor(Int, y), floor(Int, x)
        fy, fx = y - i0, x - j0
        v = 0.0
        for (dj, wj) in ((0, 1 - fx), (1, fx)), (di, wi) in ((0, 1 - fy), (1, fy))
            w = wi * wj
            w == 0 && continue
            ii = clamp(i0 + di, 1, nr)
            jj = clamp(j0 + dj, 1, nc)
            v += w * a[ii, jj]
        end
        out[i, j] = v
    end
    return out
end

"""
    inferred_type(f, argtypes::Tuple) -> Type

The return type Julia's inference derives for `f(::argtypes...)`.

`Base.infer_return_type` would be the direct spelling, but it does not exist before Julia 1.11 and
this package supports 1.10 — using it made every `lts` CI job error rather than fail, which is how
the gap surfaced. `Base.return_types` is available on both and returns a vector of candidates, one
per matching method; these call sites all have a single method, so the sole element is the answer.
"""
function inferred_type(f, argtypes::Tuple)
    ts = Base.return_types(f, argtypes)
    length(ts) == 1 || error("expected one method for $f$(argtypes), inference gave $(length(ts))")
    return only(ts)
end
